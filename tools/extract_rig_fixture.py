#!/usr/bin/env python3
# =====================================================================
# extract_rig_fixture.py -- turn a rig_tour.py capture into a replay
# fixture for the host suite.
#
#   python3 tools/extract_rig_fixture.py data/serial/tour_<ts>.log
#
# Parses every [RAW] telemetry line (fset, v, i, pf - the model's whole
# feature identity), derives the ground-truth condition from the machine
# signature (fset 0 = stopped; phase loss drops pf), and writes:
#   tests/host/rig_tour_fixture.csv   human-readable artifact
#   tests/host/rig_tour_fixture.h     C++ table the replay test consumes
#
# Truth rule (verified against the tour's own stage markers below):
#   fset is the SETPOINT - the operator preset speed=10 while the motor
#   was still stopped (17:27:10), so the running state comes from the
#   current draw: standby ~0.14 A vs running ~0.6-0.9 A.
#   i   < 0.3              -> op_stopped
#   i  >= 0.3, pf >= 0.53  -> speed_1
#   i  >= 0.3, pf <  0.53  -> speed_1_phase_loss
# Cadence: [RAW] prints every PRINT_PERIOD_MS (2 s) and the monitor
# feeds at FEED_PERIOD_MS (1 Hz), so each fixture row = 2 feed steps
# (node_runtime.cpp tick(): poll 400 ms, print 2 s, feed 1 s).
# =====================================================================
import os
import re
import sys

RX = re.compile(r"\[([\d:]+)\] \[RAW\] ts_ms=\d+"
                r" fset=([\d.eE+-]+) v=([\d.eE+-]+)"
                r" i=([\d.eE+-]+) pf=([\d.eE+-]+)")
PF_SPLIT = 0.53          # speed_1 sits ~0.56-0.57; phase loss ~0.49
I_RUN = 0.3              # standby current ~0.14 A; running ~0.6-0.9 A
START = "17:26:46"       # the rig's 's' press; earlier rows are pre-learning

NAMES = {0: "op_stopped", 1: "speed_1", 2: "speed_1_phase_loss"}
KINDS = {0: "normal", 1: "normal", 2: "fault"}


def wall_s(hms):
    h, m, s = (int(x) for x in hms.split(":"))
    return h * 3600 + m * 60 + s


def truth_of(fset, pf, i):
    if i < I_RUN:
        return 0
    return 1 if pf >= PF_SPLIT else 2


def flit(x):
    """C++ float literal: 0 -> 0.0f, 10 -> 10.0f, 0.5 -> 0.5f."""
    s = f"{x:.6g}"
    if '.' not in s and 'e' not in s.lower():
        s += '.0'
    return s + 'f'


def main():
    if len(sys.argv) < 2:
        print("usage: extract_rig_fixture.py <tour.log>")
        sys.exit(1)
    here = os.path.dirname(__file__)
    out_dir = os.path.normpath(os.path.join(here, "..", "tests", "host"))

    rows = []
    for line in open(sys.argv[1], encoding="utf-8", errors="replace"):
        m = RX.search(line)
        if not m:
            continue
        t = wall_s(m.group(1))
        if t < wall_s(START):
            continue
        fset, v, i, pf = (float(m.group(k)) for k in (2, 3, 4, 5))
        rows.append((t, fset, v, i, pf, truth_of(fset, pf, i)))
    if not rows:
        print("no [RAW] lines parsed - is this a tour log?")
        sys.exit(1)

    # ---- boundary report: truth changes vs the tour's stage markers ----
    print(f"rows: {len(rows)}  span: "
          f"{rows[0][0] // 3600:02d}:{rows[0][0] % 3600 // 60:02d}:"
          f"{rows[0][0] % 60:02d} .. "
          f"{rows[-1][0] // 3600:02d}:{rows[-1][0] % 3600 // 60:02d}:"
          f"{rows[-1][0] % 60:02d}")
    bounds = [(rows[0][5], rows[0][0])]
    for r in rows:
        if r[5] != bounds[-1][0]:
            bounds.append((r[5], r[0]))
    for tr, t in bounds:
        print(f"  truth {NAMES[tr]:20s} from "
              f"{t // 3600:02d}:{t % 3600 // 60:02d}:{t % 60:02d}")

    # ---- CSV artifact ----
    csv = os.path.join(out_dir, "rig_tour_fixture.csv")
    with open(csv, "w", encoding="utf-8") as f:
        f.write("wall_hms,fset,v,i,pf,truth\n")
        for t, fset, v, i, pf, tr in rows:
            f.write(f"{t // 3600:02d}:{t % 3600 // 60:02d}:{t % 60:02d},"
                    f"{fset:.6g},{v:.6g},{i:.6g},{pf:.6g},{NAMES[tr]}\n")
    print(f"wrote {csv}")

    # ---- C++ table ----
    hdr = os.path.join(out_dir, "rig_tour_fixture.h")
    with open(hdr, "w", encoding="utf-8") as f:
        f.write("// GENERATED by tools/extract_rig_fixture.py - do not edit.\n")
        f.write(f"// Source: {os.path.basename(sys.argv[1])} [{START} .. end],"
                f" {len(rows)} rows, 1 row = 2 monitor feed steps (1 Hz).\n")
        f.write("#pragma once\nnamespace rigfix {\n")
        f.write("struct Row { int wall; float fset, v, i, pf; int truth; };\n")
        f.write(f"inline const int N_ROWS = {len(rows)};\n")
        f.write("inline const Row ROWS[] = {\n")
        for t, fset, v, i, pf, tr in rows:
            f.write(f"  {{{t},{flit(fset)},{flit(v)},{flit(i)},{flit(pf)},{tr}}},\n")
        f.write("};\ninline const char* truthName(int t) {\n")
        for tr, name in NAMES.items():
            f.write(f"  if (t == {tr}) return \"{name}\";\n")
        f.write("  return \"?\";\n}\n")
        f.write("inline const char* truthKind(int t) {\n")
        for tr, kind in KINDS.items():
            f.write(f"  if (t == {tr}) return \"{kind}\";\n")
        f.write("  return \"normal\";\n}\n")
        f.write("}  // namespace rigfix\n")
    print(f"wrote {hdr}")


if __name__ == "__main__":
    main()
